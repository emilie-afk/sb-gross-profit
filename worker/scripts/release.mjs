#!/usr/bin/env node
/**
 * release.mjs — deploys the Worker with the private business rules injected
 * ==========================================================================
 * The rules (supplier costs, discount tiers, SKU and vendor mapping rules) are not
 * in this public repository. This script reads them from a local file, writes a
 * generated, git-ignored wrangler config (wrangler.release.toml) that adds
 *   [define] __GP_PRIVATE_RULES__ = "<the rules JSON as a string>"
 * to the committed wrangler.toml, runs `wrangler deploy` with it, and deletes it.
 *
 *   node scripts/release.mjs --rules <file> [--env staging] [--dry-run] [--keep]
 *
 *   --rules     the private rules JSON (required; never committed, never uploaded elsewhere)
 *   --env       a wrangler environment (e.g. staging); default: the top-level (production) Worker
 *   --dry-run   build only (`wrangler deploy --dry-run --outdir .wrangler/release-dry-run`) and check that
 *               the bundle carries the rules; nothing is deployed
 *   --keep      keep wrangler.release.toml afterwards (it contains the rules: delete it yourself)
 *
 * The script never prints rule values: only the rules version, key count and a
 * sha256 fingerprint. The invented test rules are refused (their version starts
 * with "synthetic").
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const WORKER = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = path.join(WORKER, 'wrangler.toml');
const GENERATED = path.join(WORKER, 'wrangler.release.toml');
const DRY_OUT = path.join(WORKER, '.wrangler', 'release-dry-run');

function args(argv) {
  const o = { env: null, dryRun: false, keep: false, rules: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--rules') o.rules = argv[++i];
    else if (a === '--env') o.env = argv[++i];
    else if (a === '--dry-run') o.dryRun = true;
    else if (a === '--keep') o.keep = true;
    else throw new Error(`unknown argument: ${a}`);
  }
  if (!o.rules) throw new Error('--rules <file> is required');
  if (o.env !== null && !/^[a-z][a-z0-9-]*$/.test(o.env)) throw new Error('--env must be a wrangler environment name');
  return o;
}

/** Validates the rules with the same check every runtime uses; returns the minified JSON text. */
export async function loadRules(file) {
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch { throw new Error('rules file not readable'); }
  let doc;
  try { doc = JSON.parse(text); } catch { throw new Error('rules file is not valid JSON'); }
  const { setPrivateRules, hasPrivateRules, privateRules, _clearPrivateRules } = await import(pathToFileURL(path.join(WORKER, '..', 'shared', 'privateRules.js')).href);
  const previous = hasPrivateRules() ? privateRules() : null;   // validate without disturbing a registered set
  try { setPrivateRules(doc); } catch (e) { throw new Error(`rules file rejected (${e.message})`); }
  finally { if (previous) setPrivateRules(previous); else _clearPrivateRules(); }
  if (String(doc.version || '').toLowerCase().startsWith('synthetic')) throw new Error('these are the invented test rules, not the private rules');
  return JSON.stringify(doc);
}

/** The committed config plus a [define] for the top level and, when deploying one, for that environment. */
export function generatedConfig(baseText, rulesJson, env) {
  if (/^\s*\[(env\.[^\]]+\.)?define\]/m.test(baseText)) throw new Error('wrangler.toml already has a [define] table; merge it into this script first');
  // A TOML basic string holding the JS expression: a string literal with the rules JSON.
  const value = JSON.stringify(JSON.stringify(JSON.parse(rulesJson)));
  const head = '# GENERATED by scripts/release.mjs. Contains the private rules: never commit, delete after use.\n';
  // Root tables must come before any [env.*] table so they stay top-level: insert [define] ahead of the first [env.
  const first = baseText.search(/^\[\[?env\./m);
  const top = `[define]\n__GP_PRIVATE_RULES__ = ${value}\n\n`;
  let out = first === -1 ? `${baseText}\n${top}` : `${baseText.slice(0, first)}${top}${baseText.slice(first)}`;
  if (env) out += `\n[env.${env}.define]\n__GP_PRIVATE_RULES__ = ${value}\n`;
  return head + out;
}

function wrangler(cmdArgs) {
  const isWin = process.platform === 'win32';
  const r = spawnSync(isWin ? 'npx.cmd' : 'npx', ['wrangler', ...cmdArgs], { cwd: WORKER, stdio: 'inherit', shell: isWin });
  return r.status ?? 1;
}

async function main() {
  const o = args(process.argv.slice(2));
  const rules = await loadRules(o.rules);
  const doc = JSON.parse(rules);
  const fp = crypto.createHash('sha256').update(rules).digest('hex').slice(0, 12);
  console.log(`Private rules: version ${doc.version}, ${Object.keys(doc).length} keys, fingerprint ${fp}`);
  fs.writeFileSync(GENERATED, generatedConfig(fs.readFileSync(BASE, 'utf8'), rules, o.env), { mode: 0o600 });
  let status = 1;
  try {
    const envArgs = o.env ? ['--env', o.env] : [];
    if (o.dryRun) {
      fs.rmSync(DRY_OUT, { recursive: true, force: true });
      status = wrangler(['deploy', '--config', 'wrangler.release.toml', ...envArgs, '--dry-run', '--outdir', path.relative(WORKER, DRY_OUT)]);
      if (status === 0) {
        const bundle = fs.readdirSync(DRY_OUT).filter(f => f.endsWith('.js')).map(f => fs.readFileSync(path.join(DRY_OUT, f), 'utf8')).join('\n');
        // The code's `typeof __GP_PRIVATE_RULES__` is replaced by the rules literal, and the rules (seen
        // here through one of their keys) are in the bundle.
        const carries = !/typeof __GP_PRIVATE_RULES__/.test(bundle) && bundle.includes('skuGrammar');
        console.log(carries ? 'Dry run: the bundle carries the private rules (nothing deployed).' : 'Dry run: the bundle does NOT carry the private rules.');
        fs.rmSync(DRY_OUT, { recursive: true, force: true });
        if (!carries) status = 1;
      }
    } else {
      status = wrangler(['deploy', '--config', 'wrangler.release.toml', ...envArgs]);
    }
  } finally {
    if (!o.keep) fs.rmSync(GENERATED, { force: true });
  }
  process.exitCode = status;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(e => { console.error(`release: ${e.message}`); process.exitCode = 1; });
}
